/* LA Associates — "Where to buy" page: map, filters and "near me".
   The list of places is static HTML generated by tools/build-stores.py, so the
   page works without this script. Everything here is progressive enhancement.
   Leaflet (self-hosted) loads only when the map scrolls into view. */
(function () {
  "use strict";

  var lang = document.documentElement.lang === "bg" ? "bg" : "en";
  var T = {
    bg: {
      all: "Всички",
      city: "Град",
      allCities: "Всички градове",
      types: "Вид обект",
      nearMe: "Близо до мен",
      locating: "Търсим местоположението ви…",
      located: "Подредено по разстояние. Най-близо: ",
      away: "от вас",
      geoError: "Не успяхме да определим местоположението ви. Проверете разрешенията на браузъра.",
      showing: function (n, total) { return "Показани " + n + " от " + total + " обекта."; },
      none: "Няма обекти, които отговарят на избраното.",
      details: "Подробности",
      directions: "Маршрут",
      you: "Вие сте тук",
      mapError: "Картата не можа да се зареди. Всички обекти са изброени по-долу."
    },
    en: {
      all: "All",
      city: "City",
      allCities: "All cities",
      types: "Type of place",
      nearMe: "Near me",
      locating: "Finding your location…",
      located: "Sorted by distance. Nearest: ",
      away: "away",
      geoError: "We couldn't get your location. Please check your browser's permissions.",
      showing: function (n, total) { return "Showing " + n + " of " + total + " places."; },
      none: "No places match your selection.",
      details: "Details",
      directions: "Directions",
      you: "You are here",
      mapError: "The map couldn't be loaded. Every place is listed below."
    }
  }[lang];

  var stores = [].slice.call(document.querySelectorAll(".store"));
  if (!stores.length) return;

  var placed = stores.filter(function (el) { return el.hasAttribute("data-lat"); });
  var groups = [].slice.call(document.querySelectorAll(".stores__group"));
  var mapEl = document.getElementById("map");
  var tools = document.getElementById("wtb-tools");
  var status = document.getElementById("wtb-status");
  var filter = { type: "all", city: "all" };

  var map, markers = {}, youMarker, leafletLoading;

  function latLng(el) {
    return [parseFloat(el.getAttribute("data-lat")), parseFloat(el.getAttribute("data-lng"))];
  }
  function text(el, sel) {
    var node = el.querySelector(sel);
    return node ? node.textContent.trim() : "";
  }
  function say(message) {
    if (status) status.textContent = message;
  }

  // ---------------------------------------------------------------- map
  var PIN = '<svg viewBox="0 0 30 40" aria-hidden="true"><path d="M15 0C6.7 0 0 6.6 0 14.8 0 25.9 15 40 15 40s15-14.1 15-25.2C30 6.6 23.3 0 15 0z"/><circle cx="15" cy="14.5" r="5.5" fill="#fff"/></svg>';

  function loadLeaflet() {
    if (leafletLoading) return leafletLoading;
    leafletLoading = new Promise(function (resolve, reject) {
      var css = document.createElement("link");
      css.rel = "stylesheet";
      css.href = "/assets/vendor/leaflet/leaflet.css";
      document.head.appendChild(css);
      var js = document.createElement("script");
      js.src = "/assets/vendor/leaflet/leaflet.js";
      js.onload = function () { initMap(); resolve(); };
      js.onerror = function () {
        say(T.mapError);
        if (mapEl) mapEl.hidden = true;
        reject(new Error("Leaflet failed to load"));
      };
      document.head.appendChild(js);
    });
    return leafletLoading;
  }

  function popup(el) {
    var box = document.createElement("div");
    box.className = "map-popup";
    var name = document.createElement("strong");
    name.textContent = text(el, ".store__name");
    var addr = document.createElement("span");
    addr.textContent = text(el, ".store__addr");
    var links = document.createElement("span");
    links.className = "map-popup__links";
    var details = document.createElement("a");
    details.href = "#" + el.id;
    details.textContent = T.details;
    details.addEventListener("click", function () { map.closePopup(); });
    var dir = document.createElement("a");
    dir.href = "https://www.google.com/maps/dir/?api=1&destination=" + latLng(el).join(",");
    dir.target = "_blank";
    dir.rel = "noopener";
    dir.textContent = T.directions;
    links.appendChild(details);
    links.appendChild(dir);
    box.appendChild(name);
    box.appendChild(addr);
    box.appendChild(links);
    return box;
  }

  function initMap() {
    var L = window.L;
    var fallback = mapEl.querySelector(".wtb__map-fallback");
    if (fallback) fallback.remove();

    // Wheel zoom stays off until the map is used, so scrolling the page
    // past it never gets hijacked.
    map = L.map(mapEl, { scrollWheelZoom: false });
    map.once("focus click", function () { map.scrollWheelZoom.enable(); });
    L.tileLayer("https://tile.openstreetmap.org/{z}/{x}/{y}.png", {
      maxZoom: 19,
      attribution: '&copy; <a href="https://www.openstreetmap.org/copyright" target="_blank" rel="noopener">OpenStreetMap</a>'
    }).addTo(map);

    var icon = L.divIcon({ className: "map-pin", html: PIN, iconSize: [30, 40], iconAnchor: [15, 40], popupAnchor: [0, -36] });
    placed.forEach(function (el) {
      var name = text(el, ".store__name");
      markers[el.id] = L.marker(latLng(el), { icon: icon, title: name, alt: name, riseOnHover: true })
        .bindPopup(popup(el));
    });
    syncMarkers();
    fitTo(visiblePlaced());
  }

  function visiblePlaced() {
    return placed.filter(function (el) { return !el.parentNode.hidden; });
  }

  function syncMarkers() {
    if (!map) return;
    placed.forEach(function (el) {
      var marker = markers[el.id];
      if (el.parentNode.hidden) map.removeLayer(marker);
      else marker.addTo(map);
    });
  }

  function fitTo(els, extra) {
    if (!map) return;
    var points = els.map(latLng);
    if (extra) points.push(extra);
    if (!points.length) return;
    if (points.length === 1) map.setView(points[0], 15);
    else map.fitBounds(points, { padding: [40, 40], maxZoom: 15 });
  }

  if (mapEl && placed.length) {
    if ("IntersectionObserver" in window) {
      var io = new IntersectionObserver(function (entries) {
        if (entries[0].isIntersecting) {
          io.disconnect();
          loadLeaflet();
        }
      }, { rootMargin: "200px" });
      io.observe(mapEl);
    } else {
      loadLeaflet();
    }
  }

  // "Show on map" buttons in the list (hidden until this script runs)
  placed.forEach(function (el) {
    var btn = el.querySelector(".store__show");
    if (!btn || !mapEl) return;
    btn.hidden = false;
    btn.addEventListener("click", function () {
      loadLeaflet().then(function () {
        mapEl.scrollIntoView({ block: "center" });
        map.setView(latLng(el), 16);
        markers[el.id].openPopup();
        mapEl.focus({ preventScroll: true });
      });
    });
  });

  // ---------------------------------------------------------------- filters
  function apply() {
    var shown = 0;
    stores.forEach(function (el) {
      var city = el.getAttribute("data-city");
      var ok = (filter.type === "all" || el.getAttribute("data-type") === filter.type) &&
               // Online shops deliver everywhere, so a city filter keeps them.
               (filter.city === "all" || !city || city === filter.city);
      el.parentNode.hidden = !ok;
      if (ok) shown++;
    });
    groups.forEach(function (g) {
      var n = g.querySelectorAll("li:not([hidden])").length;
      g.hidden = n === 0;
      var count = g.querySelector(".stores__count");
      if (count) count.textContent = n;
    });
    syncMarkers();
    fitTo(visiblePlaced());
    say(shown ? T.showing(shown, stores.length) : T.none);
  }

  function chip(label, value) {
    var b = document.createElement("button");
    b.type = "button";
    b.className = "chip";
    b.textContent = label;
    b.setAttribute("aria-pressed", value === filter.type ? "true" : "false");
    b.addEventListener("click", function () {
      filter.type = value;
      [].forEach.call(b.parentNode.children, function (c) {
        c.setAttribute("aria-pressed", c === b ? "true" : "false");
      });
      apply();
    });
    return b;
  }

  var types = [];
  stores.forEach(function (el) {
    var type = el.getAttribute("data-type");
    if (types.indexOf(type) < 0) types.push(type);
  });
  var cityGroups = groups.filter(function (g) {
    return g.querySelector("[data-city]");
  });

  if (tools) {
    if (types.length > 1) {
      var chips = document.createElement("div");
      chips.className = "chips";
      chips.setAttribute("role", "group");
      chips.setAttribute("aria-label", T.types);
      chips.appendChild(chip(T.all, "all"));
      types.forEach(function (type) {
        var sample = document.querySelector('.store[data-type="' + type + '"] .store__type');
        chips.appendChild(chip(sample.textContent, type));
      });
      tools.appendChild(chips);
    }

    if (cityGroups.length > 1) {
      var label = document.createElement("label");
      label.className = "wtb__city";
      var caption = document.createElement("span");
      caption.className = "visually-hidden";
      caption.textContent = T.city;
      var select = document.createElement("select");
      var any = document.createElement("option");
      any.value = "all";
      any.textContent = T.allCities;
      select.appendChild(any);
      cityGroups.forEach(function (g) {
        var opt = document.createElement("option");
        opt.value = g.getAttribute("data-group");
        opt.textContent = g.querySelector(".stores__city").firstChild.textContent.trim();
        select.appendChild(opt);
      });
      select.addEventListener("change", function () {
        filter.city = select.value;
        apply();
      });
      label.appendChild(caption);
      label.appendChild(select);
      tools.appendChild(label);
    }

    if (placed.length && mapEl && "geolocation" in navigator) {
      var near = document.createElement("button");
      near.type = "button";
      near.className = "btn btn--ghost wtb__near";
      near.textContent = T.nearMe;
      near.addEventListener("click", locate);
      tools.appendChild(near);
    }

    tools.hidden = !tools.children.length;
  }

  // ---------------------------------------------------------------- near me
  // The position is used only in this browser tab: it is never stored or sent.
  function km(a, b) {
    var rad = Math.PI / 180;
    var dLat = (b[0] - a[0]) * rad, dLng = (b[1] - a[1]) * rad;
    var h = Math.pow(Math.sin(dLat / 2), 2) +
            Math.cos(a[0] * rad) * Math.cos(b[0] * rad) * Math.pow(Math.sin(dLng / 2), 2);
    return 12742 * Math.asin(Math.sqrt(h));
  }

  function formatKm(d) {
    var locale = lang === "bg" ? "bg-BG" : "en-GB";
    if (d < 1) return Math.max(50, Math.round(d * 20) * 50) + " m";
    return d.toLocaleString(locale, { maximumFractionDigits: d < 10 ? 1 : 0 }) + (lang === "bg" ? " км" : " km");
  }

  function locate() {
    say(T.locating);
    navigator.geolocation.getCurrentPosition(function (pos) {
      var me = [pos.coords.latitude, pos.coords.longitude];
      var dist = {};
      placed.forEach(function (el) {
        dist[el.id] = km(me, latLng(el));
        var tag = el.querySelector(".store__dist");
        if (!tag) {
          tag = document.createElement("span");
          tag.className = "store__dist";
          el.querySelector(".store__type").after(tag);
        }
        tag.textContent = formatKm(dist[el.id]) + " " + T.away;
      });

      // Nearest place first within each city; nearest city first overall.
      // The online group (no distances) stays last.
      var nearest = function (g) {
        var best = Infinity;
        [].forEach.call(g.querySelectorAll("[data-lat]"), function (el) { best = Math.min(best, dist[el.id]); });
        return best;
      };
      groups.forEach(function (g) {
        var list = g.querySelector(".stores__list");
        [].slice.call(list.children)
          .sort(function (a, b) {
            var x = a.querySelector(".store"), y = b.querySelector(".store");
            return (dist[x.id] || Infinity) - (dist[y.id] || Infinity);
          })
          .forEach(function (li) { list.appendChild(li); });
      });
      var parent = groups[0].parentNode;
      groups.slice()
        .sort(function (a, b) { return nearest(a) - nearest(b); })
        .forEach(function (g) { parent.appendChild(g); });

      var closest = visiblePlaced().sort(function (a, b) { return dist[a.id] - dist[b.id]; });
      if (closest.length) {
        say(T.located + text(closest[0], ".store__name") + ", " + formatKm(dist[closest[0].id]) + ".");
      }
      // Frame the visitor plus the nearest place and anything else close by.
      var around = closest.filter(function (el, i) { return i === 0 || dist[el.id] <= 20; }).slice(0, 5);
      loadLeaflet().then(function () {
        map.closePopup();
        if (youMarker) map.removeLayer(youMarker);
        youMarker = window.L.circleMarker(me, { radius: 8, color: "#fff", weight: 3, fillColor: "#1a73e8", fillOpacity: 1 })
          .bindTooltip(T.you).addTo(map);
        fitTo(around, me);
      });
    }, function () {
      say(T.geoError);
    }, { timeout: 10000, maximumAge: 300000 });
  }
})();
